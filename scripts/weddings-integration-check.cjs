const { Buffer } = require("node:buffer");
// Isolated local replica set only. Never loads .env.local or connects to Atlas.
const assert = require("node:assert/strict");
const { randomBytes, createDecipheriv, createHash } = require("node:crypto");
const { MongoClient, ObjectId, Long } = require("mongodb");
const { MongoMemoryReplSet } = require("mongodb-memory-server");
const { sourceLoader } = require("./scaffold-contract-check.cjs");

async function main() {
  const replica = await MongoMemoryReplSet.create({ replSet: { count: 1 }, binary: { version: "8.2.6" }, instanceOpts: [{ launchTimeout: 30000 }] });
  const client = new MongoClient(replica.getUri());
  try {
    await client.connect();
    const db = client.db("weddings_isolated_test"), load = sourceLoader();
    const origin = "http://localhost:3100", key = randomBytes(32).toString("hex");
    process.env.APP_ORIGIN = origin; process.env.NODE_ENV = "development";
    const { createAccountAuth, prepareAccountIndexes } = load("src/modules/accounts/server/auth.ts");
    await prepareAccountIndexes(db);
    const queued = [];
    const auth = createAccountAuth(db, client, { origin, secret: randomBytes(32).toString("hex") }, async input => queued.push(input));
    const authHeaders = { origin, "content-type": "application/json", "x-kalyanapura-client-ip": "127.0.0.1" };
    const authRequest = (path, body, cookie) => auth.handler(new globalThis.Request(origin + "/api/auth/" + path, { method: body ? "POST" : "GET", headers: { ...authHeaders, ...(cookie ? { cookie } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) }));
    async function member(email) {
      const credentials = { name: "Synthetic Member", email, password: "Synthetic-password-123" };
      assert.equal((await authRequest("sign-up/email", credentials)).status, 200);
      await auth.handler(new globalThis.Request(queued.find(item => item.email === email).url));
      const response = await authRequest("sign-in/email", credentials);
      assert.equal(response.status, 200);
      const cookie = response.headers.getSetCookie().find(value => value.includes("session_token=")).split(";")[0];
      const session = await (await authRequest("get-session", undefined, cookie)).json();
      return { cookie, account: { id: session.user.id, name: session.user.name, email, emailVerified: true } };
    }
    const first = await member("first@example.com"), second = await member("second@example.com"), third = await member("third@example.com");
    const { createWeddingService } = load("src/modules/weddings/server/service.ts");
    const service = createWeddingService(db, client, () => key);
    const sharedErrors = { "@/server/http/errors": load("src/server/http/errors.ts"), "./errors": load("src/server/http/errors.ts"), "@/server/config": load("src/server/config.ts") };
    const handlersFor = target => sourceLoader({ ...sharedErrors, "./auth": { getAuth: async () => auth }, "next/navigation": { redirect: () => { throw new Error("Unexpected page redirect in REST handler"); } }, "./service": { getWeddingService: async () => target } })("src/modules/weddings/server/handlers.ts");
    const handlers = handlersFor(service);
    const input = { brideName: "  Synthetic Bride  ", groomName: "Synthetic Groom", weddingDate: "2027-02-14", location: " Kochi ", title: "Together begins here" };
    const request = (cookie, body = input, extra = {}) => new globalThis.Request(origin + "/api/v1/weddings", { method: "POST", headers: { ...authHeaders, "X-KP-Request": "1", ...(cookie ? { cookie } : {}), ...extra }, body: typeof body === "string" ? body : JSON.stringify(body) });
    const readRequest = cookie => new globalThis.Request(origin + "/api/v1/me", { headers: cookie ? { cookie } : {} });
    assert.equal((await handlers.handleCreateWedding(request())).status, 401);
    assert.equal((await handlers.handleMe(readRequest())).status, 401);
    assert.equal((await handlers.handleMe(readRequest("kalyanapura.session_token=forged"))).status, 401);
    assert.equal((await handlers.handleGetWedding(readRequest(), new ObjectId().toHexString())).status, 401);
    const before = await (await handlers.handleMe(readRequest(first.cookie))).json();
    assert.equal(before.data.nextAction, "create_or_join");
    assert.equal(before.data.membership, null);
    const unverified = sourceLoader({ "@/modules/accounts/server/session": { getAccount: async () => ({ ...first.account, emailVerified: false }) }, "./service": { getWeddingService: async () => service } })("src/modules/weddings/server/handlers.ts");
    assert.equal((await unverified.handleCreateWedding(request(first.cookie))).status, 403);
    assert.equal((await (await unverified.handleMe(readRequest(first.cookie))).json()).data.nextAction, "verify_email");
    for (const extra of [{ origin: "https://foreign.example" }, { "X-KP-Request": "" }, { "sec-fetch-site": "cross-site" }]) assert.equal((await handlers.handleCreateWedding(request(first.cookie, input, extra))).status, 403);
    assert.equal((await handlers.handleCreateWedding(request(first.cookie, input, { "content-type": "text/plain" }))).status, 415);
    assert.equal((await handlers.handleCreateWedding(request(first.cookie, "{"))).status, 400);
    assert.equal((await handlers.handleCreateWedding(request(first.cookie, " ".repeat(262145)))).status, 413);
    for (const invalid of [{ ...input, weddingDate: "2027-02-30" }, { ...input, weddingDate: "0000-01-01" }, { ...input, brideName: " " }, { ...input, location: "x".repeat(501) }, { ...input, weddingId: new ObjectId().toHexString() }]) {
      const response = await handlers.handleCreateWedding(request(first.cookie, invalid));
      assert.equal(response.status, 422);
      assert.ok((await response.json()).error.fields.length);
    }
    assert.equal(await db.collection("weddings").countDocuments(), 0);
    const created = await handlers.handleCreateWedding(request(first.cookie));
    assert.equal(created.status, 201);
    const result = (await created.json()).data;
    assert.equal(result.wedding.brideName, "Synthetic Bride");
    assert.equal(result.wedding.location, "Kochi");
    assert.equal(result.membership.role, "admin");
    assert.equal(result.membership.status, "active");
    assert.equal(result.membership.weddingId, result.wedding.id);
    assert.equal(created.headers.get("Location"), "/api/v1/weddings/" + result.wedding.id);
    assert.equal(created.headers.get("X-Resource-Version"), "1");
    assert.equal(created.headers.get("Cache-Control"), "private, no-store");
    assert.match(created.headers.get("X-Request-Id"), /^req_/);
    assert.doesNotMatch(JSON.stringify(result), /token|Quota|writeFence|createdByUserId/);
    const stored = await db.collection("weddings", { promoteLongs: false }).findOne({ _id: new ObjectId(result.wedding.id) });
    assert.equal(stored.website.isPublished, false);
    assert.ok(Long.isLong(stored.writeFence)); assert.equal(stored.writeFence.toString(), "1");
    assert.equal(stored.version, 1); assert.equal(stored.updatedAt.getTime(), stored.createdAt.getTime());
    assert.equal(stored.mediaQuota.limitBytes.toString(), "0");
    const envelope = stored.gallery.tokenCiphertext;
    const decipher = createDecipheriv("aes-256-gcm", Buffer.from(key, "hex"), Buffer.from(envelope.iv, "base64url"));
    decipher.setAAD(Buffer.from("weddings:" + result.wedding.id + ":gallery:1")); decipher.setAuthTag(Buffer.from(envelope.tag, "base64url"));
    const token = Buffer.concat([decipher.update(Buffer.from(envelope.ciphertext, "base64url")), decipher.final()]).toString("utf8");
    assert.equal(Buffer.from(token, "base64url").length, 32);
    assert.equal(createHash("sha256").update(token).digest("hex"), stored.gallery.tokenHash);
    const savedMember = await db.collection("wedding_members").findOne({ userId: first.account.id });
    assert.equal(typeof savedMember.userId, "string", "Membership stores the canonical auth ID without BSON conversion");
    const own = await handlers.handleGetWedding(readRequest(first.cookie), result.wedding.id);
    assert.equal(own.status, 200); assert.deepEqual((await own.json()).data, result);
    assert.equal((await handlers.handleGetWedding(readRequest(second.cookie), result.wedding.id)).status, 404);
    assert.equal((await handlers.handleGetWedding(readRequest(first.cookie), "invalid")).status, 400);
    assert.equal((await handlers.handleCreateWedding(request(first.cookie))).status, 409);
    const races = await Promise.all(Array.from({ length: 5 }, () => handlers.handleCreateWedding(request(second.cookie))));
    assert.equal(races.filter(value => value.status === 201).length, 1);
    assert.equal(races.filter(value => value.status === 409).length, 4);
    assert.equal(await db.collection("weddings").countDocuments(), 2, "Losing creates leave no orphan wedding");
    assert.equal(await db.collection("wedding_members").countDocuments(), 2);
    const me = await (await handlers.handleMe(readRequest(first.cookie))).json();
    assert.equal(me.data.nextAction, "dashboard");
    assert.equal(me.data.membership.id, result.membership.id);
    await db.collection("wedding_members").updateOne({ userId: second.account.id }, { $set: { status: "removing" } });
    assert.equal((await (await handlers.handleMe(readRequest(second.cookie))).json()).data.nextAction, "membership_cleanup");
    const removedContext = await service.context(second.account);
    assert.equal(removedContext.wedding, null);
    assert.equal((await handlers.handleGetWedding(readRequest(second.cookie), removedContext.membership.weddingId)).status, 404);
    assert.equal((await handlers.handleCreateWedding(request(second.cookie))).status, 409);
    const { CapabilityConfigurationError } = load("src/server/config.ts");
    const missingKey = createWeddingService(db, client, () => { throw new CapabilityConfigurationError("Test encryption"); });
    assert.equal((await missingKey.context(first.account)).wedding.id, result.wedding.id, "Read does not require the gallery encryption capability");
    assert.equal((await handlersFor(missingKey).handleCreateWedding(request(third.cookie))).status, 503);
    const repositoryModule = load("src/modules/weddings/server/repository.ts");
    const failingFactory = sourceLoader({ "./repository": { ...repositoryModule, weddingRepository: database => ({ ...repositoryModule.weddingRepository(database), members: { insertOne: async () => { throw new Error("internal-secret-failure"); } } }) } })("src/modules/weddings/server/service.ts").createWeddingService;
    const failed = await handlersFor(failingFactory(db, client, () => key)).handleCreateWedding(request(third.cookie));
    assert.equal(failed.status, 500); assert.doesNotMatch(JSON.stringify(await failed.json()), /internal-secret-failure/);
    assert.equal(await db.collection("weddings").countDocuments(), 2, "A failure after the coordination write rolls back the whole creation");
    await assert.rejects(() => db.collection("wedding_members").insertOne({ userId: "invalid" }), error => error.code === 121);
    assert.equal((await handlers.handleMe(readRequest(first.cookie))).status, 200);
    await authRequest("sign-out", {}, first.cookie);
    assert.equal((await handlers.handleMe(readRequest(first.cookie))).status, 401);
    assert.equal((await handlers.handleGetWedding(readRequest(first.cookie), result.wedding.id)).status, 401);
    await db.collection("session").updateMany({ userId: new ObjectId(third.account.id) }, { $set: { expiresAt: new Date(0) } });
    assert.equal((await handlers.handleCreateWedding(request(third.cookie))).status, 401);
    const { calendarDay, daysUntilWedding } = load("src/modules/weddings/schemas.ts");
    assert.ok(calendarDay("2024-02-29")); assert.ok(!calendarDay("2023-02-29")); assert.ok(calendarDay("0001-01-01"));
    assert.equal(daysUntilWedding("2027-02-14", new Date("2027-02-13T18:29:59Z")), 1);
    assert.equal(daysUntilWedding("2027-02-14", new Date("2027-02-13T18:30:00Z")), 0);
    assert.equal(daysUntilWedding("2027-02-14", new Date("2027-02-14T18:30:00Z")), -1);
    console.log("PASS: real isolated auth → atomic wedding creation → live membership/dashboard context → logout; concurrency rollback, foreign-ID denial, removing/expired/forged sessions, CSRF/body validation, encrypted defaults, safe response contracts and Kolkata calendar boundaries.");
    console.log("NOT RUN: live Atlas writes, providers, invitations, editing and future planning workflows.");
  } finally { await client.close(); await replica.stop(); }
}
main().catch(error => { console.error("FAIL: isolated wedding checks:", error.message.replace(/https?:\/\/\S+/g, "[redacted URL]")); process.exitCode = 1; });
